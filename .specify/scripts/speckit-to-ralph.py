#!/usr/bin/env python3
"""Spec Kit -> Ralph bridge. Single source of truth after handoff: ralph/task_status.json.
usage: speckit-to-ralph.py FEATURE_DIR [--force-archive]   |   speckit-to-ralph.py --converge
"""
import json, re, sys, shutil, datetime, pathlib
ROOT = pathlib.Path.cwd()
RALPH = ROOT / "ralph"; STATUS = RALPH / "task_status.json"
now = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")

def die(msg, code=2): print("REFUSED: " + msg, file=sys.stderr); sys.exit(code)

def in_flight(d):
    if d.get("completeEpic") or d.get("status") in ("completed", "complete", "done"): return False
    items = d.get("todos") or d.get("tasks") or []
    return any(not t.get("passes") for t in items) or d.get("status") == "in_progress" and bool(items)

def convert(fdir):
    fdir = pathlib.Path(fdir).resolve()
    spec, plan, tasks = (fdir / n for n in ("spec.md", "plan.md", "tasks.md"))
    for p in (spec, plan, tasks):
        if not p.exists(): die(f"missing {p}")
    if STATUS.exists():
        cur = json.loads(STATUS.read_text())
        if in_flight(cur): die(f"Ralph epic '{cur.get('epic')}' is in flight (status={cur.get('status')}). Finish or explicitly restart it first.")
        arch = RALPH / "archive" / f"{cur.get('epic') or 'prev'}-{now[:10]}"
        arch.mkdir(parents=True, exist_ok=True)
        for n in ("task_status.json", "epic.md", "qa-report.md"):
            if (RALPH / n).exists(): shutil.copy2(RALPH / n, arch / n)
        print(f"archived previous completed epic -> {arch.relative_to(ROOT)}")
    st = spec.read_text(); pt = plan.read_text(); tt = tasks.read_text()
    reqs = re.findall(r"\*\*(FR-\d+)\*\*:?\s*(.+)", st)
    scs = re.findall(r"\*\*(SC-\d+)\*\*:?\s*(.+)", st)
    tlines = re.findall(r"^- \[[ xX]\] (T\d+)\s*(.*)$", tt, re.M)
    if not reqs or not tlines: die("could not parse FR-### requirements or T### tasks")
    epic = fdir.name
    requirements = [{"id": f"REQ-{r[3:]}", "title": t.strip(), "todoIds": [], "status": "pending", "sourceId": r} for r, t in reqs]
    rmap = {r["sourceId"]: r for r in requirements}
    acs = [{"id": f"AC-{s[3:]}", "text": t.strip(), "sourceId": s} for s, t in scs]
    todos = []
    for tid, text in tlines:
        frs = re.findall(r"FR-\d+", text)
        clean = re.sub(r"\[(P|US\d+)\]\s*", "", text)
        clean = re.sub(r"\s*\((?:FR|SC)-[\d, FRSC-]+\)", "", clean).strip()
        reqids = [rmap[f]["id"] for f in frs if f in rmap]
        for f in frs:
            if f in rmap: rmap[f]["todoIds"].append(tid.lower())
        todos.append({"id": tid.lower(), "content": clean, "requirementIds": reqids,
                      "acceptanceCriteria": [f"AC-{s[3:]}" for s in re.findall(r"SC-\d+", text)],
                      "status": "pending", "passes": False, "notes": "", "sourceTask": tid})
    orphans = [r["id"] for r in requirements if not r["todoIds"]]
    if orphans: die(f"requirements with no task: {orphans} (fix tasks.md / rerun analyze)")
    title = re.search(r"^# (.+)$", st, re.M)
    (RALPH).mkdir(exist_ok=True)
    (RALPH / "epic.md").write_text(
        f"# {title.group(1) if title else epic}\n\n> Generated by speckit-to-ralph from `{fdir.relative_to(ROOT)}` at {now}. "
        "Spec Kit files are read-only input; ralph/task_status.json is the execution source of truth.\n\n"
        f"## Spec\n\n{st}\n\n## Implementation plan\n\n{pt}\n\n## Task breakdown (input only)\n\n{tt}\n")
    data = {"epic": epic, "branch": f"ralph/{epic}", "baseBranch": "main", "status": "in_progress", "loop": 0,
            "persona": "planning", "completeEpic": False, "selected": None, "canonicalStatusFile": "ralph/task_status.json",
            "sourceArtifacts": [str(p.relative_to(ROOT)) for p in (spec, plan, tasks)],
            "generatedBy": "speckit-to-ralph", "requirements": requirements, "todos": todos,
            "acceptanceCriteria": acs, "outOfScope": [], "openQuestions": [], "blockers": [], "lastUpdated": now}
    STATUS.write_text(json.dumps(data, indent=2) + "\n")
    print(f"epic={epic} REQs={len(requirements)} ACs={len(acs)} todos={len(todos)}\nwrote ralph/epic.md, ralph/task_status.json\nStart Ralph now? (requires Roy's go)")

def converge():
    if not STATUS.exists(): die("no ralph/task_status.json")
    qa = RALPH / "qa-report.md"
    if not qa.exists(): die("no ralph/qa-report.md")
    d = json.loads(STATUS.read_text())
    gaps = re.findall(r"^- (?:\[ \] )?(?:GAP|FAIL)[:\s]+(.+)$", qa.read_text(), re.M | re.I)
    existing = {t["content"] for t in d.get("todos", [])}
    n = len(d.get("todos", [])); added = []
    for g in gaps:
        if g.strip() in existing: continue
        n += 1; tid = f"gap-{n:03d}"
        d.setdefault("todos", []).append({"id": tid, "content": g.strip(), "requirementIds": [], "acceptanceCriteria": [],
            "status": "pending", "passes": False, "notes": f"added by /speckit.converge from qa-report.md {now}"})
        added.append(tid)
    if added:
        d["status"] = "in_progress"; d["completeEpic"] = False; d["persona"] = "planning"; d["lastUpdated"] = now
        STATUS.write_text(json.dumps(d, indent=2) + "\n")
    print(f"gaps added: {added or 'none'}")

if __name__ == "__main__":
    a = sys.argv[1:]
    if a == ["--converge"]: converge()
    elif len(a) == 1: convert(a[0])
    else: print(__doc__); sys.exit(1)
